"""Package the saved Games/DTF appearance palettes for the stage extension."""
import json
from pathlib import Path
from showcase_catalog import published_themes
from literal_colors import literal_palette

ROOT = Path(__file__).resolve().parent.parent
catalog = {theme['id']: theme for theme in published_themes(ROOT, 'appearance-themes.json')}
presets = []
for key in ('games', 'dtf'):
    theme = catalog[key]
    modes = {}
    for mode, source in theme['modes'].items():
        tokens = {'--theme-color-background': source['--theme-color-background']}
        if key == 'games':
            for name in ('--theme-color-brand-header', '--theme-gradient-brand-header', '--theme-color-accent'):
                tokens[name] = source[name]
        color = source['--theme-color-backdrop-pattern']
        tokens['--theme-gradient-pattern'] = f'linear-gradient({color}, {color})'
        tokens['--theme-size-pattern'] = source['--theme-size-backdrop-pattern']
        tokens['--theme-opacity-pattern'] = str(float(source['--theme-opacity-backdrop-pattern'].rstrip('%')) / 100)
        tokens['--theme-image-pattern'] = f'@pattern:{key}'
        if key == 'games':
            tokens = json.loads((ROOT / 'showcase/games-extension-palette.json').read_text())[mode]
        tokens = literal_palette(tokens)
        modes[mode] = tokens
    presets.append({'id': f'preset-{key}', 'name': theme['name'], 'base': 'classic', 'revision': 4 if key == 'games' else 2, **({'migrateModes': ['dark']} if key == 'games' else {}), **modes})
output = ROOT / 'extension/osnova-tokens/preset-palettes.js'
output.write_text('// Generated by scripts/package_extension_presets.py from the saved appearance catalog.\n'
                  'globalThis.OsnovaPresetPalettes = ' + json.dumps(presets, ensure_ascii=False, indent=2) + ';\n', encoding='utf-8')
print('Packaged saved appearance themes: ' + ', '.join(item['name'] for item in presets))
