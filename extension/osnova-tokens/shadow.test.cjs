const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const context = vm.createContext({});
vm.runInContext(fs.readFileSync(`${__dirname}/shadow.js`, 'utf8'), context);
const api = context.OsnovaShadow;
const source = ' 0 4px 20px rgba(103, 103, 103, .32),  0 0 0 1px var(--gray-33) ';
const layers = api.parse(source);
assert.equal(layers.length, 2);
assert.equal(api.serialize(layers), source);
layers[0].color = 'rgba(12, 34, 56, 0.45)'; layers[0].dirty = true;
assert.equal(api.serialize(layers), source.replace('rgba(103, 103, 103, .32)', 'rgba(12, 34, 56, 0.45)'));
layers[0].x = 999; layers[0].blur = 200; layers[0].inset = true;
assert.equal(api.serialize(layers), source.replace('rgba(103, 103, 103, .32)', 'rgba(12, 34, 56, 0.45)'), 'serializer changes only the color, even if geometry fields mutate');
layers[1].color = '#abcdef'; layers[1].dirty = true;
assert.ok(api.serialize(layers).includes('0 0 0 1px #abcdef'));
const inset = api.parse('inset 0 -1px .5px -2px #0008');
inset[0].color = 'rgba(1, 2, 3, .4)'; inset[0].dirty = true;
assert.equal(api.serialize(inset), 'inset 0 -1px .5px -2px rgba(1, 2, 3, .4)');
const first = api.parse('#0008 1px 2px'); first[0].color = '#123456'; first[0].dirty = true;
assert.equal(api.serialize(first), '#123456 1px 2px');
const implicit = api.parse('0 2px 3px'); implicit[0].color = '#123456'; implicit[0].dirty = true;
assert.equal(api.serialize(implicit), '0 2px 3px #123456');
assert.equal(api.serialize(api.parse('none')), 'none');
assert.throws(() => api.parse('0 2px -1px black'));
console.log('Passed: only colors change; exact geometry, inset, layer order/count, var references, spacing and numeric notation preserved.');
