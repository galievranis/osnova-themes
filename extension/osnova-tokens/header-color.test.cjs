const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const context = vm.createContext({});
for (const name of ['color.js', 'header-color.js']) vm.runInContext(fs.readFileSync(`${__dirname}/${name}`, 'utf8'), context);
const api = context.OsnovaHeaderColor;
const parseColor = value => context.OsnovaColor.parse(value);
const sample = (gradient, fill = '#ffffff', width = 1200) => api.sample({ gradient, fill, background: '#ffffff', width, height: 60, parseColor });
assert.equal(sample('none', '#123456'), '#123456');
assert.equal(sample('linear-gradient(90deg, #ff0000, #0000ff)'), '#800080');
assert.equal(sample('linear-gradient(to right, #ff0000, #0000ff)'), '#800080');
assert.equal(sample('linear-gradient(to bottom, #ff0000, #0000ff)'), '#F90006', 'top edge is sampled, not center of header');
assert.equal(sample('linear-gradient(to top, #ff0000, #0000ff)'), '#0600F9');
assert.equal(sample('linear-gradient(#ff000080, #ff000080)', '#0000ff'), '#80007F');
assert.equal(sample('linear-gradient(#ff000080, #ff000080), linear-gradient(#0000ff, #0000ff)', '#ffffff'), '#80007F', 'first layer paints on top');
assert.equal(sample('linear-gradient(#ff0000, transparent)', '#ffffff'), '#FF0606', 'transparent interpolation stays premultiplied');
const radial = sample('radial-gradient(ellipse 50% 100% at 50% 0%, #ff0000, #0000ff)');
assert.ok(parseInt(radial.slice(1, 3), 16) > 245);
assert.ok(parseInt(radial.slice(5), 16) < 10);
const gta = 'radial-gradient(ellipse 42% 170% at 12% 105%, #661F50, transparent), radial-gradient(ellipse 58% 145% at 45% -38%, #652D78, transparent), radial-gradient(ellipse 54% 210% at 93% 10%, #2E3779, transparent)';
const dark = sample(gta, '#3F1B60');
assert.notEqual(dark, '#3F1B60', 'export includes actual layered gradient');
assert.match(dark, /^#[A-F0-9]{6}$/);
assert.notEqual(sample('radial-gradient(ellipse 200px 100px at 50px 0px, #ff0000, #0000ff)', '#3F1B60', 390), sample('radial-gradient(ellipse 200px 100px at 50px 0px, #ff0000, #0000ff)', '#3F1B60', 1440), 'pixel-sized ellipses depend on header geometry');
assert.throws(() => sample('url("https://example.com/image.png")'));
console.log(`Passed: top-center averaging, linear angles, alpha compositing, CSS layer order, premultiplied transparent stops, radial ellipses and responsive geometry. GTA sample: ${dark}`);
