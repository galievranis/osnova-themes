const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
(async () => {
  const context = vm.createContext({});
  for (const file of ['preset-palettes.js', 'presets.js']) vm.runInContext(fs.readFileSync(`${__dirname}/${file}`, 'utf8'), context);
  const origin = 'https://themes-gta.dtf.osnova.app';
  const libraryKey = `osnova-tokens:library:${origin}`;
  const existing = { active: 'mine', profiles: [{ id: 'mine', name: 'Моя тема', base: 'gta' }] };
  const saved = { [libraryKey]: existing, [`osnova-tokens:v1:${origin}:gta`]: { light: { '--theme-color-accent': '#abcdef' } } };
  const storage = { get: async key => ({ [key]: saved[key] }), set: async data => Object.assign(saved, data) };
  await context.OsnovaPresets.ensure(storage, origin, file => `chrome-extension://abcdefghijklmnopabcdefghijklmnop/${file}`);
  assert.equal(saved[libraryKey].active, 'mine');
  assert.equal(saved[libraryKey].profiles.find(x => x.id === 'mine').base, 'classic', 'existing My Theme is rebased without deleting edits');
  assert.equal(saved[libraryKey].profiles.length, 3);
  const games = saved[`osnova-tokens:v1:${origin}:preset-games`];
  const dtf = saved[`osnova-tokens:v1:${origin}:preset-dtf`];
  assert.equal(games.light['--theme-color-brand-header'], '#D2F447');
  assert.equal(games.dark['--theme-color-brand-header'], '#29164D');
  const gamesKeys = ['--theme-color-background', '--theme-color-brand-header', '--theme-gradient-brand-header', '--theme-color-accent', '--theme-gradient-pattern', '--theme-image-pattern', '--theme-opacity-pattern', '--theme-size-pattern'].sort();
  assert.deepEqual(Object.keys(games.light).sort(), gamesKeys, 'light Games stays unchanged');
  assert.equal(games.dark['--theme-color-text-primary'], '#F5F1FF');
  assert.equal(games.dark['--theme-color-text-tertiary'], '#B9B4C3');
  assert.ok(!JSON.stringify(games).includes('color-mix('));
  assert.equal(games.dark['--theme-color-button-minimal-hover'], 'rgba(73, 67, 93, 1)');
  assert.equal(games.dark['--theme-color-button-minimal-pressed'], 'rgba(94, 86, 120, 1)');
  assert.ok(!Object.keys(games.dark).some(key => /positive|negative|rating|^--theme-shadow/.test(key)), 'status colors and shadow geometry stay Classic');
  assert.equal(dtf.light['--theme-color-background'], '#F4FAFF');
  assert.equal(dtf.dark['--theme-color-accent'], undefined);
  const dtfKeys = ['--theme-color-background', '--theme-gradient-pattern', '--theme-image-pattern', '--theme-opacity-pattern', '--theme-size-pattern'].sort();
  for (const mode of ['light', 'dark']) assert.deepEqual(Object.keys(dtf[mode]).sort(), dtfKeys, 'DTF overrides only the page background and pattern');
  assert.match(games.light['--theme-image-pattern'], /patterns\/games.svg/);
  assert.match(dtf.dark['--theme-image-pattern'], /patterns\/dtf.svg/);
  assert.equal(games.light['--theme-opacity-pattern'], '0.1');
  assert.equal(games.dark['--theme-opacity-pattern'], '0.15');
  assert.ok(!JSON.stringify(games).includes('--classic-gray-'), 'local-only gray aliases are resolved');
  assert.ok(!JSON.stringify(dtf).includes('backdrop-pattern'), 'local pattern aliases map to existing stage tokens');
  games.dark['--theme-color-accent'] = '#123456';
  saved[libraryKey].profiles.find(x => x.id === 'preset-games').name = 'Игры — моя версия';
  await context.OsnovaPresets.ensure(storage, origin, x => x);
  assert.equal(saved[libraryKey].profiles.length, 3, 'no duplicates');
  assert.equal(games.dark['--theme-color-accent'], '#123456', 'preset edits survive reinstallation');
  assert.equal(saved[libraryKey].profiles.find(x => x.id === 'preset-games').name, 'Игры — моя версия');
  assert.equal(saved[`osnova-tokens:v1:${origin}:gta`].light['--theme-color-accent'], '#abcdef');
  const gamesKey = `osnova-tokens:v1:${origin}:preset-games`;
  saved[gamesKey] = { light: { '--theme-color-text-primary': '#ffffff' }, dark: { '--theme-color-button-minimal': '#ff0000' }, presetRevision: 1 };
  await context.OsnovaPresets.ensure(storage, origin, x => x);
  assert.equal(saved[gamesKey].light['--theme-color-text-primary'], undefined, 'old Games text overrides are removed');
  assert.notEqual(saved[gamesKey].dark['--theme-color-button-minimal'], '#ff0000', 'old Games controls are replaced by harmonized colors');
  saved[gamesKey] = { ...saved[gamesKey], presetRevision: 2, light: { '--theme-color-accent': '#123456' } };
  await context.OsnovaPresets.ensure(storage, origin, x => x);
  assert.equal(saved[gamesKey].light['--theme-color-accent'], '#123456', 'dark-only migration preserves the user light palette');
  const dtfKey = `osnova-tokens:v1:${origin}:preset-dtf`;
  saved[dtfKey] = { light: { '--theme-color-accent': '#ff0000' }, dark: { '--theme-color-brand-header': '#ff0000' }, enabled: true };
  await context.OsnovaPresets.ensure(storage, origin, x => x);
  assert.equal(saved[dtfKey].light['--theme-color-accent'], undefined, 'one-time migration removes old DTF accent overrides');
  assert.equal(saved[dtfKey].dark['--theme-color-brand-header'], undefined, 'DTF header inherits Classic');
  saved[dtfKey].light['--theme-color-background'] = '#abcdef';
  await context.OsnovaPresets.ensure(storage, origin, x => x);
  assert.equal(saved[dtfKey].light['--theme-color-background'], '#abcdef', 'subsequent launches preserve new edits');
  await assert.rejects(() => context.OsnovaPresets.ensure(storage, 'https://other.test', x => x));
  console.log('Passed: saved palettes and patterns, mode-specific values, stage token mapping, preserving active/user-edited themes, idempotent installation.');
})().catch(error => { console.error(error); process.exitCode = 1; });
